/**
 * Writes tests/fixtures/evaluations.json: reference evaluateBoard() values
 * from the TypeScript engine, used to check that other engines (the C++ port)
 * evaluate identically.
 *
 * Usage: pnpm --filter @connect4/api export:evaluations
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type { Board, Player } from "@connect4/core";
import { applyMove, checkWin, legalMoves, makeEmptyBoard, otherPlayer } from "@connect4/core";

import { evaluateBoard } from "../src/engine/evaluate";
import { loadPositions, loadWins, rowsToBoard } from "../../../tests/fixtures/load";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../../../tests/fixtures/evaluations.json");
const RANDOM_GAMES = 40;

function toRows(board: Board): string[] {
  const rows: string[] = [];
  for (let r = 0; r < 6; r++) {
    rows.push(board.slice(r * 7, r * 7 + 7).map((c) => (c === 0 ? "." : String(c))).join(""));
  }
  return rows;
}

// Deterministic LCG so the file is reproducible.
let seed = 20261103;
function random(): number {
  seed = (Math.imul(seed, 1103515245) + 12345) & 0x7fffffff;
  return seed / 2 ** 31;
}

type Entry = { id: string; rows: string[]; scores: { "1": number; "2": number } };

function entry(id: string, board: Board): Entry {
  return { id, rows: toRows(board), scores: { "1": evaluateBoard(board, 1), "2": evaluateBoard(board, 2) } };
}

const entries: Entry[] = [];

for (const p of loadPositions()) entries.push(entry(p.id, rowsToBoard(p.rows) as Board));
for (const w of loadWins()) entries.push(entry(`wins/${w.id}`, rowsToBoard(w.rows) as Board));

// Random playouts, sampled every few plies, including the final (possibly won) board.
for (let g = 0; g < RANDOM_GAMES; g++) {
  let board = makeEmptyBoard();
  let player: Player = 1;
  for (let ply = 1; ; ply++) {
    const moves = legalMoves(board);
    if (moves.length === 0) break;
    board = applyMove(board, moves[Math.floor(random() * moves.length)], player)!.board;
    const over = checkWin(board, player) || legalMoves(board).length === 0;
    if (ply % 5 === 0 || over) entries.push(entry(`random-${g}-ply-${ply}`, board));
    if (over) break;
    player = otherPlayer(player);
  }
}

const json = {
  $comment:
    "Generated by apps/api/scripts/export-evaluations.ts. Rows are top (row 0) to bottom. scores[p] is evaluateBoard(board, p).",
  positions: entries
};

writeFileSync(OUT, JSON.stringify(json, null, 2) + "\n");
console.log(`Wrote ${entries.length} evaluations to ${OUT}`);
