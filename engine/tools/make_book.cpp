// Generates engine/src/book_data.inc: full-window search results for every
// position with up to --discs discs, at --depth plies.
//
// Usage: connect4_make_book [--discs N] [--depth N] [--out PATH]
//
// Positions and their mirror images share one entry. Each search uses the
// engine itself with the book disabled, so book scores are exactly what a
// fixed-depth search would return.

#include <algorithm>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <map>
#include <vector>

#include "connect4/book.hpp"
#include "connect4/search.hpp"

using namespace connect4;

namespace {

int argValue(int argc, char** argv, const char* name, int fallback) {
    for (int i = 1; i + 1 < argc; ++i) {
        if (std::strcmp(argv[i], name) == 0) return std::atoi(argv[i + 1]);
    }
    return fallback;
}

const char* argString(int argc, char** argv, const char* name, const char* fallback) {
    for (int i = 1; i + 1 < argc; ++i) {
        if (std::strcmp(argv[i], name) == 0) return argv[i + 1];
    }
    return fallback;
}

/// Every non-terminal position reachable with at most `maxDiscs` discs,
/// keyed by canonical key.
void collect(const Position& pos, int maxDiscs, std::map<Bitboard, Position>& out) {
    if (pos.moves() > maxDiscs || pos.lastMoverWon() || pos.isFull()) return;
    const Bitboard key = canonicalKey(pos);
    if (out.count(key)) return;
    // Store the orientation whose key is canonical.
    out.emplace(key, pos.key() == key ? pos : pos.mirrored());
    for (int col = 0; col < kWidth; ++col) {
        if (!pos.canPlay(col)) continue;
        Position child = pos;
        child.play(col);
        collect(child, maxDiscs, out);
    }
}

}  // namespace

int main(int argc, char** argv) {
    const int maxDiscs = argValue(argc, argv, "--discs", 3);
    const int depth = argValue(argc, argv, "--depth", 16);
    const char* outPath = argString(argc, argv, "--out", "book_data.inc");

    std::map<Bitboard, Position> positions;
    collect(Position(), maxDiscs, positions);
    std::fprintf(stderr, "%zu positions with up to %d discs, depth %d\n", positions.size(), maxDiscs, depth);

    Engine engine(24);  // 256 MiB: generation runs offline
    std::vector<BookEntry> entries;
    const auto start = std::chrono::steady_clock::now();
    int done = 0;
    for (const auto& [key, pos] : positions) {
        const SearchResult r = engine.chooseMove(pos, {depth, 0, false});
        BookEntry e{key, {}};
        for (int col = 0; col < kWidth; ++col) {
            const auto& s = r.columnScores[static_cast<std::size_t>(col)];
            e.scores[static_cast<std::size_t>(col)] = s ? *s : kNoScore;
        }
        entries.push_back(e);
        const double elapsed =
            std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        std::fprintf(stderr, "\r%d/%zu (%.0f s)", ++done, positions.size(), elapsed);
    }
    std::fprintf(stderr, "\n");

    std::FILE* out = std::fopen(outPath, "w");
    if (!out) {
        std::fprintf(stderr, "cannot write %s\n", outPath);
        return 1;
    }
    std::fprintf(out, "// Generated by connect4_make_book --discs %d --depth %d. Do not edit.\n",
                 maxDiscs, depth);
    std::fprintf(out, "// Scores are fixed-depth search results (heuristic), not solved values.\n");
    std::fprintf(out, "constexpr int kBookDepth = %d;\n", depth);
    std::fprintf(out, "constexpr int kBookMaxDiscs = %d;\n", maxDiscs);
    std::fprintf(out, "constexpr BookEntry kBookEntries[] = {\n");
    for (const auto& e : entries) {  // std::map iteration: already sorted by key
        std::fprintf(out, "    {0x%llxULL, {", static_cast<unsigned long long>(e.key));
        for (int col = 0; col < kWidth; ++col) {
            const std::int32_t s = e.scores[static_cast<std::size_t>(col)];
            if (col) std::fprintf(out, ", ");
            if (s == kNoScore) std::fprintf(out, "kNoScore");
            else std::fprintf(out, "%d", s);
        }
        std::fprintf(out, "}},\n");
    }
    std::fprintf(out, "};\n");
    std::fclose(out);
    std::fprintf(stderr, "wrote %zu entries to %s\n", entries.size(), outPath);
    return 0;
}
