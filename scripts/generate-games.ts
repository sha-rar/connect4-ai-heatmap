/**
 * Writes tests/fixtures/games.json: complete games with the legal moves and
 * game status after every ply, as the TypeScript rules (@connect4/core)
 * compute them. The TypeScript and C++ rule tests both replay this file, so
 * any disagreement between the two implementations fails a test.
 *
 * Usage: pnpm fixtures:games
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type { Board, Player } from "../packages/core/src/index";
import { COLS, ROWS, applyMove, getCell, getStatus, legalMoves, makeEmptyBoard, otherPlayer } from "../packages/core/src/index";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../tests/fixtures/games.json");

type Direction = "horizontal" | "vertical" | "diagonal" | "anti-diagonal";
type Game = {
  id: string;
  moves: string;
  legal: string[];
  status: "won" | "draw";
  winner: 0 | Player;
  direction?: Direction;
  rows: string[];
};

// Deterministic PRNG (mulberry32) so the file is reproducible.
let seed = 20261103;
function random(): number {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

function toRows(board: Board): string[] {
  return Array.from({ length: ROWS }, (_, r) =>
    Array.from({ length: COLS }, (_, c) => String(getCell(board, r, c)).replace("0", ".")).join("")
  );
}

/** Direction of a four-in-a-row through (row, col) for `player`. */
function winDirection(board: Board, row: number, col: number, player: Player): Direction {
  const steps: Array<[Direction, number, number]> = [
    ["horizontal", 0, 1],
    ["vertical", 1, 0],
    ["diagonal", 1, 1],
    ["anti-diagonal", -1, 1]
  ];
  const owns = (r: number, c: number) => r >= 0 && r < ROWS && c >= 0 && c < COLS && getCell(board, r, c) === player;
  for (const [name, dr, dc] of steps) {
    let run = 1;
    for (let k = 1; owns(row + dr * k, col + dc * k); k++) run++;
    for (let k = 1; owns(row - dr * k, col - dc * k); k++) run++;
    if (run >= 4) return name;
  }
  throw new Error("no four-in-a-row through the last move");
}

/** Play random legal moves until the game ends. */
function playRandomGame(): Omit<Game, "id"> {
  let board = makeEmptyBoard();
  let player: Player = 1;
  let moves = "";
  const legal: string[] = [];
  for (;;) {
    const options = legalMoves(board);
    const col = options[Math.floor(random() * options.length)];
    const result = applyMove(board, col, player)!;
    board = result.board;
    moves += col;
    legal.push(legalMoves(board).join(""));

    const status = getStatus(board, player);
    if (status.state === "won") {
      return {
        moves,
        legal,
        status: "won",
        winner: status.winner,
        direction: winDirection(board, result.row, col, player),
        rows: toRows(board)
      };
    }
    if (status.state === "draw") return { moves, legal, status: "draw", winner: 0, rows: toRows(board) };
    player = otherPlayer(player);
  }
}

const games: Game[] = [];
const add = (kind: string, game: Omit<Game, "id">) => {
  const n = games.filter((g) => g.id.startsWith(kind)).length + 1;
  games.push({ id: `${kind}-${String(n).padStart(2, "0")}`, ...game });
};

// Random games, then extra games until every win direction and both winners
// appear a few times and there are some draws (full boards).
const RANDOM_GAMES = 60;
const MIN_EACH = 4;
const MIN_DRAWS = 3;
for (let i = 0; i < RANDOM_GAMES; i++) add("random", playRandomGame());

const count = (pred: (g: Game) => boolean) => games.filter(pred).length;
const directions: Direction[] = ["horizontal", "vertical", "diagonal", "anti-diagonal"];
for (let attempts = 0; attempts < 200_000; attempts++) {
  const missingDirection = directions.filter((d) => count((g) => g.direction === d) < MIN_EACH);
  const missingDraws = count((g) => g.status === "draw") < MIN_DRAWS;
  const missingWinner2 = count((g) => g.winner === 2) < MIN_EACH;
  if (!missingDirection.length && !missingDraws && !missingWinner2) break;

  const game = playRandomGame();
  if (game.status === "draw" && missingDraws) add("draw", game);
  else if (game.direction && missingDirection.includes(game.direction)) add(game.direction, game);
  else if (game.winner === 2 && missingWinner2) add("winner2", game);
}

if (count((g) => g.status === "draw") < MIN_DRAWS) throw new Error("not enough drawn games found");

writeFileSync(
  OUT,
  JSON.stringify(
    {
      $comment:
        "Generated by scripts/generate-games.ts from the TypeScript rules. moves are zero-based columns from the empty board. legal[i] lists the legal columns after move i (empty once the board is full). The game ends on the last move with status and winner; rows is the final board, top row first.",
      games
    },
    null,
    2
  ) + "\n"
);
console.log(`wrote ${games.length} games to ${OUT}`);
